import fs from "node:fs";
import path from "node:path";

const CHARS = Array.from(
  "一二三四五六七八九十兩零點分半整刻時上下午中晚早夜現在正"
);

const dataDir = path.resolve("node_modules/hanzi-writer-data");
const out = {};
const missing = [];

for (const ch of CHARS) {
  const file = path.join(dataDir, ch + ".json");
  if (!fs.existsSync(file)) { missing.push(ch); continue; }
  const raw = JSON.parse(fs.readFileSync(file, "utf8"));
  out[ch] = { strokes: raw.strokes, medians: raw.medians };
}
if (missing.length) { console.error("MISSING CHARS:", missing.join(" ")); process.exit(1); }

const header = `// AUTO-GENERATED by scripts/gen-stroke-data.mjs - do not edit by hand.
// Source: hanzi-writer-data (derived from the "Make Me a Hanzi" project, itself
// derived from the Arphic PL fonts). Licensed under Arphic Public License + LGPL.
// See node_modules/hanzi-writer-data/{APL,ARPHICPL.TXT}.
//
// Coordinate space: the Make Me a Hanzi 1024x1024 EM square, Y axis pointing UP,
// baseline near y=0. To render in screen space apply \`scale(1,-1) translate(0,-900)\`
// (see geometry.ts -> dataMatrix). \`strokes\` are per-stroke outline paths (closed
// shapes); \`medians\` are ordered centre-line points per stroke, in correct stroke
// order and direction. The arrays are index-aligned: medians[i] skeletons strokes[i].
`;

const body =
  header +
  "\nexport interface GlyphData {\n" +
  "  /** Per-stroke outline path strings (closed shapes). */\n" +
  "  strokes: string[];\n" +
  "  /** Per-stroke ordered centre-line points, index-aligned with strokes. */\n" +
  "  medians: [number, number][][];\n" +
  "}\n\n" +
  "export const STROKE_DATA: Record<string, GlyphData> = " +
  JSON.stringify(out) +
  ";\n";

fs.writeFileSync("src/calligraphy/data/strokeData.ts", body);
console.log(`Wrote ${Object.keys(out).length} glyphs, ${(Buffer.byteLength(body) / 1024).toFixed(1)} KB`);
